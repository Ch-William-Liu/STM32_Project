static void set_pair(FreqPair_t pair)
{
  g_pair = pair;
  if (pair == PAIR_30_31) {g_f0_hz = 30000U; g_f1_hz = 31000;}
  else                    {g_f0_hz = 45000U; g_f1_hz = 46000;}
} // end function set_pair

static void ascii_to_bits(const char *s, char *out, uint32_t outMax, uint32_t *outLen)
{
  uint32_t  n = 0;
  while (*s && (n + 8U) < outMax)
  {
    uint8_t c = (uint8_t)(*s++);
    for (int b = 7; b >= 0; b--)
    {
      out[n++] = ((c >> b) & 1U) ? '1' : '0';
    } // end for
  } // end while
  out[n] = '\0';
  *outLen = n;
} // end function ascii_to_bits

static uint32_t get_tim6_clock_hz(void)
{
  uint32_t pclk1 = HAL_RCC_GetPCLK1Freq();
  uint32_t ppre1 = (RCC->CFGR >> RCC_CFGR_PPRE1_Pos) & 0x7U;
  if (ppre1 >= 4U) return pclk1 * 2U;
  else              return pclk1;
} // end function get_tim6_clock_hz

static void set_output_freq_hz(uint32_t f_out_hz)
{
  uint32_t target_update = f_out_hz * LUT_SIZE;         // DAC update rate
  if (target_update == 0U || tim6_clk_hz == 0U) return;

  uint32_t div = tim6_clk_hz / target_update;
  if (div == 0U) div = 1U;

  uint32_t arr = div - 1U;
  if (arr > 0xFFFFU) arr = 0xFFFFU;

  __HAL_TIM_SET_AUTORELOAD(&htim6, (uint16_t)arr);
  __HAL_TIM_SET_COUNTER(&htim6 , 0U);
} // end function set_output_freq_hz

static void start_output(void)
{
  if (!dma_running)
  {
    HAL_DAC_Start(&hdac , DAC1_CHANNEL_1);
    HAL_DAC_Start_DMA(&hdac , DAC1_CHANNEL_1 , (uint32_t*)sineLUT , LUT_SIZE , DAC_ALIGN_12B_R);
    dma_running = 1;
  } // end if
  HAL_TIM_Base_Start(&htim6);
} // end function start_output

// during gap -> force 0V
static void stop_and_silence(void)
{
  HAL_TIM_Base_Stop(&htim6);

  if (dma_running)
  {
    HAL_DAC_Stop_DMA(&hdac , DAC1_CHANNEL_1);
    dma_running = 0;
  } // end if

  HAL_DAC_Start(&hdac , DAC1_CHANNEL_1);
  HAL_DAC_SetValue(&hdac , DAC1_CHANNEL_1 , DAC_ALIGN_12B_R , DAC_ZERO_12B);
} // end function stop_and_silence
