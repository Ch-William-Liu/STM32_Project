void MakeHannWindow(void)
{
  for (int i = 0; i < FFT_SIZE; i++)
  {
    window[i] = 0.5f - 0.5f * cosf((2.0f * PI * i) / (FFT_SIZE - 1));
  } // end for
} // end function MakeHannWindow

void ProcessFFT(uint16_t *src)
{
  float mean = 0.0f;
  for (int i = 0; i < FFT_SIZE; i++)
  {
    fftIn[i] = (float)src[i];
    mean += fftIn[i];
  } // end for

  mean /= FFT_SIZE;         // calculate mean value of fftIn

  for (int i = 0; i < FFT_SIZE; i++)
  {
    fftIn[i] = (fftIn[i] - mean) * window[i];       // de-mean and apply hanning window
  } // end for
  
  arm_rfft_fast_f32(&fftHandler , fftIn , fftOut , 0);

  mag[0] = fabs(fftOut[0]);

  for (int k = 1; k < FFT_BINS; k++)
  {
    float re = fftOut[2 * k];       // real part of FFT result
    float im = fftOut[2 * k - 1];   // image part of FFT result
    mag[k] = sqrtf(re * re + im * im);
  } // end for
} // end function ProcessFFT

void SendFFTPacket(void)
{
  static uint8_t txBuf[2 + 2 + 2 + FFT_BINS * 2 + 2];
  uint16_t idx = 0;
  uint32_t sum = 0;
  const float scale = 0.005f;

  txBuf[idx++] = 0xAA;
  txBuf[idx++] = 0x55;

  txBuf[idx++] = (uint8_t)(msgID & 0xFF);
  txBuf[idx++] = (uint8_t)((msgID >> 8) & 0xFF);

  txBuf[idx++] = (uint8_t)(FFT_BINS & 0xFF);
  txBuf[idx++] = (uint8_t)((FFT_BINS >> 8) & 0xFF);

  for (int i = 0; i < FFT_BINS; i++)
  {
    float x = mag[i] * scale;

    if (x < 0.0f) x = 0.0f;
    if (x > 65535.0f) x = 65535.0f;

    uint16_t y = (uint16_t)x;

    txBuf[idx++] = (uint8_t)(y & 0xFF);
    txBuf[idx++] = (uint8_t)((y >> 8) & 0xFF);

    sum += y;
  } // end for
  

  uint16_t crc = (uint16_t)(sum & 0xFFFF);
  txBuf[idx++] = (uint8_t)(crc & 0xFF);
  txBuf[idx++] = (uint8_t)((crc >> 8) & 0xFF);

  HAL_UART_Transmit(&huart3 , txBuf , idx , HAL_MAX_DELAY);

  msgID++;
} // end function SendFFTPacket
